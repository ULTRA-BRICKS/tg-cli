"""Capture canonical Bun letter membership, independent of Python's Unicode DB.

BUN=/path/to/bun python tests/py/fixtures/render/capture_unicode_letters.py
The supported Bun version is intentionally pinned: a changed Unicode contract
requires an explicit parity decision and a fresh reviewed table/digest.
"""

import json
import os
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
CAPTURE = r"""
import {createHash} from 'node:crypto';
if (Bun.version !== '1.4.2') throw new Error('capture requires canonical Bun 1.4.2');
const letters = /\p{L}/u;
const boundaries=[];
const membership = Buffer.alloc(0x110000);
let previous = false;
for (let cp=0; cp<0x110000; cp++) {
  const present = letters.test(String.fromCodePoint(cp));
  membership[cp] = Number(present);
  if (present !== previous) boundaries.push(cp);
  previous = present;
}
if(previous) boundaries.push(0x110000);
process.stdout.write(JSON.stringify({
  boundaries, count:membership.reduce((n,v)=>n+v,0),
  sha256:createHash('sha256').update(membership).digest('hex'),
  unicode:process.versions.unicode
}) + '\n');
"""


def main():
    data = json.loads(
        subprocess.check_output(
            [os.environ.get("BUN", "bun"), "-e", CAPTURE],
            cwd=ROOT,
        )
    )
    lines = [
        'r"""Frozen Bun 1.4.2 /\\p{L}/u membership; no Python Unicode DB dependency.',
        "",
        "Generated by tests/py/fixtures/render/capture_unicode_letters.py.",
        f"Canonical runtime reports Unicode {data['unicode']}; {data['count']} letter code points.",
        "Half-open range boundaries alternate start/end; bisect parity tests membership.",
        '"""',
        "",
        "from bisect import bisect_right",
        "",
        "# fmt: off",
        "_LETTER_BOUNDARIES = (",
    ]
    for index in range(0, len(data["boundaries"]), 8):
        lines.append(
            "    " + ", ".join(f"0x{cp:X}" for cp in data["boundaries"][index : index + 8]) + ","
        )
    lines += [
        ")",
        "# fmt: on",
        "",
        "",
        "def is_bun_letter(ch: str) -> bool:",
        '    """Match the canonical JS Unicode Letter property for one code point."""',
        "    return bisect_right(_LETTER_BOUNDARIES, ord(ch)) % 2 == 1",
        "",
    ]
    (ROOT / "src/tgcli/prefix_style/_unicode_letters.py").write_text("\n".join(lines))
    (Path(__file__).parent / "unicode_letters.json").write_text(
        json.dumps(
            {
                "bun": "1.4.2",
                "unicode": data["unicode"],
                "codepoint_count": 0x110000,
                "letter_count": data["count"],
                "membership_sha256": data["sha256"],
            },
            indent=2,
        )
        + "\n"
    )
    print(
        f"{len(data['boundaries']) // 2} ranges; {data['count']} letters; SHA256 {data['sha256']}"
    )


if __name__ == "__main__":
    main()
