#!/usr/bin/env bun
import { readFileSync, writeFileSync } from 'fs';
import { join } from 'path';
import { configSchemaText, renderConfigHelp } from '../features/config/schema';

/** The full setting reference comes from the same renderer as `tg help config`. */
export function configurationDocText(): string {
  return `<!-- Generated by bun run schema:gen. Edit features/config/schema.ts or the generator, then regenerate. -->
# Configuration

Run \`tg help config\` for the complete reference below. The aliases
\`tg config help\`, \`tg config --help\`, and \`tg config -h\` print the same help.
These commands work without credentials and do not read or create configuration files.

## Configuration files and editor support

The default directory is \`~/.config/tg-cli\`; set \`TG_CTL_CONFIG_DIR\` to use a
different directory. Settings live in \`config.yaml\`, while Telegram credentials
live in the separate \`.env\` file managed by \`tg auth\`.

Normal configuration reads and writes refresh \`config.schema.json\` beside the
YAML file and maintain this leading comment:

\`\`\`yaml
# yaml-language-server: $schema=./config.schema.json
\`\`\`

The YAML language server resolves this relative path from the YAML file's
directory. Editors using that server can provide key completion, descriptions,
and diagnostics. The comment is ignored by the runtime configuration readers.
For editor behavior, see the [YAML language server documentation](https://github.com/redhat-developer/yaml-language-server#using-a-modeline).

If the configuration is missing, a normal configuration read creates the
annotated file and schema. Help and dry-run paths do not initialize these files.
Metadata refresh is best-effort: a readable configuration remains usable if its
directory cannot be updated. Updating the modeline preserves the remaining YAML
text, including user comments; settings are not parsed and serialized again.

The schema describes the recommended scalar syntax and flags unknown keys.
It supplies editor guidance; existing runtime parsing and fallback behavior stay
the same. Use unquoted \`true\` and \`false\`, decimal integers, and one-level
settings inside the documented blocks. The reference explains legacy accepted
forms and the few fields whose defaults are chosen at runtime.

## Complete reference

\`\`\`text
${renderConfigHelp().trimEnd()}
\`\`\`

## Maintaining the generated files

The registry in [features/config/schema.ts](../features/config/schema.ts) supplies
CLI help and the schema, with defaults imported from the runtime modules. To
regenerate both this reference and the tracked schema:

\`\`\`bash
bun run schema:gen
bun run schema:check
\`\`\`

The check reports missing or stale artifacts without rewriting them. CI runs it,
and the ordinary test suite compares both tracked artifacts to the generator so
the existing remote shipping test gate also catches drift.

This repository runs Bun scripts directly and has no build step. Installation
links the checkout, and deployment fast-forwards its tracked files, so the schema
ships through those existing paths. Generation is explicit; it never stages or
commits files automatically.
`;
}

/** Return false only when check mode finds missing or stale output. */
export function syncConfigArtifact(path: string, content: string, check = false): boolean {
  let current: string | undefined;
  try {
    current = readFileSync(path, 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
  }
  if (current === content) return true;
  if (check) return false;
  writeFileSync(path, content, 'utf8');
  return true;
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const usage = 'Usage: bun scripts/generate-config-schema.ts [--check]';
  if (args.length === 1 && (args[0] === '--help' || args[0] === '-h')) {
    process.stdout.write(`${usage}\n`);
    process.exit(0);
  }
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
    console.error(usage);
    process.exit(2);
  }
  const root = join(import.meta.dir, '..');
  const check = args[0] === '--check';
  const artifacts = [
    ['config.schema.json', configSchemaText()],
    ['docs/configuration.md', configurationDocText()],
  ] as const;
  let valid = true;
  try {
    for (const [name, content] of artifacts) {
      if (!syncConfigArtifact(join(root, name), content, check)) {
        console.error(`${name} is missing or stale. Run bun run schema:gen and include the generated files.`);
        valid = false;
      }
    }
  } catch (error) {
    console.error(`Cannot ${check ? 'check' : 'generate'} configuration artifacts: ${String(error)}`);
    process.exit(1);
  }
  process.exit(valid ? 0 : 1);
}
